#!/usr/bin/env node
/**
 * Generate `src/surfaces/shell-integration-assets.ts` from the shell
 * integration scripts in `src/surfaces/shell-integration/`.
 *
 * Why embed the scripts as TypeScript string constants?
 *
 * `tsc` does NOT copy non-TS assets into `dist/`, so a packaged/installed
 * gateway used to ship without `dist/surfaces/shell-integration/*`. The
 * terminal then silently fell back to "no shell integration" mode: no OSC 633
 * prompt/command markers, so command boundaries, exit codes, working
 * directory tracking and background completion detection all degraded (or
 * stopped working) inside the Tauri app.
 *
 * Embedding makes the integration scripts impossible to lose: the runtime
 * materialises them from the bundled constants whenever the on-disk copy is
 * missing. `scripts/copy-shell-integration.mjs` still copies the real files
 * into `dist/` for users who want to read/source them directly, and
 * `src/surfaces/shell-integration-assets.test.ts` guards against the embedded
 * copies drifting away from the files.
 *
 * Usage:
 *   node scripts/embed-shell-integration.mjs           # write the module
 *   node scripts/embed-shell-integration.mjs --check   # fail if out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(here, "..");
const scriptDir = join(packageRoot, "src", "surfaces", "shell-integration");
const outFile = join(packageRoot, "src", "surfaces", "shell-integration-assets.ts");

/** @type {{ file: string, exportName: string }[]} */
const scripts = [
  { file: "bash.sh", exportName: "BASH_INTEGRATION_SCRIPT" },
  { file: "zsh.sh", exportName: "ZSH_INTEGRATION_SCRIPT" },
  { file: "pwsh.ps1", exportName: "PWSH_INTEGRATION_SCRIPT" },
];

/** Render file content as a readable array of JSON-encoded lines. */
function renderLines(content) {
  const lines = content.split("\n");
  return lines.map((line) => `  ${JSON.stringify(line)},`).join("\n");
}

const banner = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * Source: \`src/surfaces/shell-integration/*.sh|*.ps1\`
 * Regenerate: \`node scripts/embed-shell-integration.mjs\`
 *
 * These constants are the packaging-proof fallback for the shell integration
 * scripts. \`tsc\` does not copy \`.sh\`/\`.ps1\` assets into \`dist/\`, so a
 * published/installed gateway (and the Tauri desktop bundle) can end up
 * without \`dist/surfaces/shell-integration\`. Without those files the terminal
 * silently ran with no OSC 633 integration, which broke prompt detection,
 * exit codes and background-command completion. The runtime now writes these
 * embedded copies to a cache directory whenever the packaged files are
 * missing, so integration always works.
 *
 * Generated by: scripts/embed-shell-integration.mjs
 */
`;

let out = banner;
for (const { file, exportName } of scripts) {
  const content = readFileSync(join(scriptDir, file), "utf8");
  out += `\n/** Contents of \`shell-integration/${file}\` (${content.length} bytes). */\n`;
  out += `export const ${exportName}: string = [\n${renderLines(content)}\n].join("\\n");\n`;
}

out += `
/** Map of integration script filename → embedded contents. */
export const SHELL_INTEGRATION_ASSETS: Readonly<Record<string, string>> = {
  "bash.sh": BASH_INTEGRATION_SCRIPT,
  "zsh.sh": ZSH_INTEGRATION_SCRIPT,
  "pwsh.ps1": PWSH_INTEGRATION_SCRIPT,
};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    console.error(`${outFile} is missing — run: node scripts/embed-shell-integration.mjs`);
    process.exit(1);
  }
  if (current !== out) {
    console.error(
      `${outFile} is out of date with src/surfaces/shell-integration/* — run: node scripts/embed-shell-integration.mjs`,
    );
    process.exit(1);
  }
  console.log("shell-integration-assets.ts is up to date");
  process.exit(0);
}

writeFileSync(outFile, out);
console.log(`Wrote ${outFile}`);
