//! Search presentation/routing. The host search port owns command execution,
//! filesystem scope, candidate collection/ranking and limits beyond this wrapper.
use futures_util::future::BoxFuture;
use serde_json::{Value, json};
use std::sync::{Arc, LazyLock};
#[derive(Clone, Debug, PartialEq)]
pub enum SearchError {
    Error(String),
    Unavailable { reason: String, message: String },
    Thrown(Value),
}
pub type SearchPort = Arc<
    dyn for<'a> Fn(&'a str, &'a Value) -> BoxFuture<'a, Result<Value, SearchError>> + Send + Sync,
>;
pub struct SearchTool {
    port: SearchPort,
}
fn truthy(v: &Value) -> bool {
    match v {
        Value::Null => false,
        Value::Bool(v) => *v,
        Value::String(v) => !v.is_empty(),
        Value::Number(v) => v.as_f64().is_some_and(|v| v != 0.0),
        _ => true,
    }
}
fn fields(input: &Value, names: &[&str]) -> Value {
    let mut result = json!({});
    for name in names {
        if let Some(v) = input.get(*name) {
            result[*name] = v.clone();
        }
    }
    result
}
// Source-free helper generated by DeepSeek through Ollama, reviewed locally and
// checked against the actual Node path implementation by differential contracts.
fn resolve_posix(root: &str, path: &str) -> String {
    let combined = if path.starts_with('/') {
        path.to_string()
    } else if root.ends_with('/') {
        format!("{}{}", root, path)
    } else {
        format!("{}/{}", root, path)
    };
    let mut parts: Vec<&str> = Vec::new();
    for seg in combined.split('/') {
        match seg {
            "" | "." => {}
            ".." => {
                parts.pop();
            }
            _ => parts.push(seg),
        }
    }
    let mut out = String::from("/");
    out.push_str(&parts.join("/"));
    out
}
fn limit(input: Option<&Value>) -> Result<u64, SearchError> {
    let n = match input {
        None | Some(Value::Null) => 20.0,
        Some(Value::String(s)) if s.is_empty() => 20.0,
        Some(v) => v.as_f64().unwrap_or(f64::NAN),
    };
    if !n.is_finite() || n.fract() != 0.0 || n < 1.0 {
        return Err(SearchError::Error(
            "limit must be a positive integer".into(),
        ));
    }
    Ok(n.min(200.0) as u64)
}
impl SearchTool {
    pub fn new(port: SearchPort) -> Self {
        Self { port }
    }
    pub async fn execute(&self, input: &Value, context: &Value) -> Result<Value, SearchError> {
        let root = (self.port)("resolve", &fields(context, &["sessionId", "projectRoot"])).await?;
        let root = root
            .as_str()
            .ok_or_else(|| SearchError::Error("project root must be an absolute string".into()))?;
        let mut root = if truthy(&input["path"]) {
            resolve_posix(root, input["path"].as_str().unwrap_or(""))
        } else {
            root.to_owned()
        };
        let mut include = input.get("include").cloned();
        if let Ok(info) = (self.port)("stat", &json!({"path":root})).await
            && truthy(&info["isFile"])
        {
            let trimmed = root.trim_end_matches('/');
            let last = trimmed.rfind('/').unwrap_or(0);
            include = Some(json!(if trimmed.is_empty() {
                ""
            } else {
                &trimmed[last + 1..]
            }));
            root = if last == 0 {
                "/".into()
            } else if last == 1 && root.starts_with("//") {
                "//".into()
            } else {
                trimmed[..last].into()
            };
        }
        Ok(match self.run(input, &root, include).await {
            Ok(v) => v,
            Err(SearchError::Error(message)) => json!({"ok":false,"message":message}),
            Err(SearchError::Unavailable { reason, message }) => {
                json!({"ok":false,"message":message,"data":{"reason":reason}})
            }
            Err(SearchError::Thrown(_)) => json!({"ok":false,"message":"Search failed"}),
        })
    }
    async fn run(
        &self,
        input: &Value,
        root: &str,
        include: Option<Value>,
    ) -> Result<Value, SearchError> {
        let limit = limit(input.get("limit"))?;
        let files = input["mode"] == "files";
        let mut options = fields(input, &["includeIgnoredFiles"]);
        if let Some(v) = include {
            options["include"] = v;
        }
        options["root"] = json!(root);
        if let Some(v) = input.get("pattern") {
            options["query"] = v.clone();
        }
        options["limit"] = json!(limit);
        options["mode"] = json!(if files { "files" } else { "content" });
        if files {
            if let Some(v) = input.get("isRegexp") {
                options["isRegexp"] = v.clone();
            }
        } else {
            options["isRegexp"] = input
                .get("isRegexp")
                .filter(|v| !v.is_null())
                .cloned()
                .unwrap_or(json!(false));
        }
        let mut result = (self.port)("search", &options).await?;
        let correct =
            |v: &Value| v["mode"].as_str() == Some(if files { "files" } else { "content" });
        if !correct(&result) {
            return Err(SearchError::Error("Unexpected project search mode".into()));
        }
        let mut retried = None;
        if !files && result["matches"].as_array().is_some_and(Vec::is_empty) {
            let initial = truthy(&options["isRegexp"]);
            options["isRegexp"] = json!(!initial);
            if let Ok(retry) = (self.port)("search", &options).await
                && correct(&retry)
                && retry["matches"].as_array().is_some_and(|v| !v.is_empty())
            {
                result = retry;
                retried = Some(if initial { "literal" } else { "regex" });
            }
        }
        let entries = result[if files { "files" } else { "matches" }]
            .as_array()
            .ok_or_else(|| SearchError::Error("invalid host search result".into()))?;
        let n = entries.len();
        let pattern = input["pattern"].as_str().unwrap_or("");
        let suffix = if truthy(&result["limited"]) {
            format!(" (stopped at the {limit}-result limit — narrow the pattern to see the rest)")
        } else {
            String::new()
        };
        let mut message = if n == 0 {
            if files {
                format!("No files matching \"{pattern}\"")
            } else {
                format!("No matches for \"{pattern}\"")
            }
        } else if files {
            format!(
                "Found {n} file{} matching \"{pattern}\"{suffix}",
                if n == 1 { "" } else { "s" }
            )
        } else {
            format!(
                "Found {n} match{} for \"{pattern}\"{suffix}",
                if n == 1 { "" } else { "es" }
            )
        };
        if let Some(retried) = retried {
            message.push_str(&format!(" (retried as {retried})"));
        }
        let mut data = fields(input, &["pattern"]);
        data[if files { "files" } else { "matches" }] = json!(
            entries
                .iter()
                .map(|v| if files {
                    v["path"].clone()
                } else {
                    fields(v, &["file", "line", "content"])
                })
                .collect::<Vec<_>>()
        );
        Ok(json!({"ok":true,"message":message,"data":data}))
    }
}
pub fn metadata() -> &'static Value {
    static VALUE: LazyLock<Value> = LazyLock::new(|| {
        serde_json::from_str(include_str!("core-search-metadata.json"))
            .expect("search tool metadata")
    });
    &VALUE
}
