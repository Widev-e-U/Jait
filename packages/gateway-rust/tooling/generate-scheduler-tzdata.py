#!/usr/bin/env python3
"""Pack reviewed IANA 2025b TZif files for the current reference runtime.

Source: https://data.iana.org/time-zones/releases/tzdata2025b.tar.gz
Compile the standard zone files plus backward, excluding backzone, using
zic -b fat into BASE/zoneinfo. The archive checksum is verified below.
This packer never downloads or updates data implicitly.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[3]
BASE = ROOT / ".jait/artifacts/gateway-rust/scheduler/tzdb-2025b"
SOURCE = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else BASE / "zoneinfo"
OUTPUT = ROOT / "packages/gateway-rust/src/scheduler"
assert (BASE / "source/version").read_text().strip() == "2025b"
assert hashlib.sha256((BASE / "tzdata2025b.tar.gz").read_bytes()).hexdigest() == "11810413345fc7805017e27ea9fa4885fd74cd61b2911711ad038f5d28d71474"
blob = bytearray()
chunks = {}
index = []
for path in sorted(SOURCE.rglob("*")):
    if not path.is_file():
        continue
    name = path.relative_to(SOURCE).as_posix()
    data = path.read_bytes()
    assert data.startswith(b"TZif"), name
    digest = hashlib.sha256(data).hexdigest()
    if digest not in chunks:
        chunks[digest] = (len(blob), len(data))
        blob.extend(data)
    start, size = chunks[digest]
    index.append((name, start, size))
assert len(index) == 597
code = [
    "// Generated by tooling/generate-scheduler-tzdata.py from IANA tzdata 2025b.",
    "// Validated against the reference Bun 1.4.0 / ICU 78.3 data contract.",
    'pub const VERSION: &str = "2025b";',
    'pub const DATA: &[u8] = include_bytes!("scheduler-tzdata-2025b.bin");',
    'pub const INDEX: &[(&str, usize, usize)] = &[',
]
code += [f"    ({json.dumps(name)}, {start}, {size})," for name, start, size in index]
code.append("];")
OUTPUT.mkdir(parents=True, exist_ok=True)
(OUTPUT / "tzdata_2025b.rs").write_text("\n".join(code) + "\n")
(OUTPUT / "scheduler-tzdata-2025b.bin").write_bytes(blob)
(OUTPUT / "tzdata-LICENSE").write_bytes((BASE / "source/LICENSE").read_bytes())

print(json.dumps({"zones": len(index), "unique_tzif": len(chunks), "bytes": len(blob), "sha256": hashlib.sha256(blob).hexdigest()}))
