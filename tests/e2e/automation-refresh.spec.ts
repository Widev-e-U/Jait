import { test, expect } from '@playwright/test'

test('activity responses cannot replace a newer selection or refresh', async ({ page }) => {
  await page.goto('/src/e2e-fixtures/index.html')
  await page.evaluate(() => import('/src/e2e-fixtures/automation-refresh.tsx'))
  const requestCount = () => page.evaluate(() => (window as any).activityRequests.length)
  const resolve = (index: number, id: string) => page.evaluate(async ([i, value]) => {
    (window as any).resolveActivity(i, value)
    await new Promise(resolve => setTimeout(resolve, 25))
  }, [index, id] as const)
  const activities = page.getByTestId('activities')

  await page.getByRole('button', { name: 'Select A' }).click()
  await expect.poll(requestCount).toBe(1)
  await page.getByRole('button', { name: 'Refresh' }).click()
  await expect.poll(requestCount).toBe(2)
  await resolve(1, 'new-refresh')
  await expect(activities).toHaveText('new-refresh')
  await resolve(0, 'old-selection')
  await expect(activities).toHaveText('new-refresh')

  await page.getByRole('button', { name: 'Refresh' }).click()
  await expect.poll(requestCount).toBe(3)
  await page.getByRole('button', { name: 'Select B' }).click()
  await expect.poll(requestCount).toBe(4)
  await page.getByRole('button', { name: 'Select A' }).click()
  await expect.poll(requestCount).toBe(5)
  await resolve(4, 'returned-a')
  await expect(activities).toHaveText('returned-a')
  await resolve(2, 'stale-a')
  await resolve(3, 'stale-b')
  await expect(activities).toHaveText('returned-a')

  await page.getByRole('button', { name: 'Refresh' }).click()
  await page.getByRole('button', { name: 'Refresh' }).click()
  await expect.poll(requestCount).toBe(7)
  await resolve(6, 'latest')
  await expect(activities).toHaveText('latest')
  await resolve(5, 'older')
  await expect(activities).toHaveText('latest')

  await page.getByRole('button', { name: 'Refresh' }).click()
  await expect.poll(requestCount).toBe(8)
  await page.getByRole('button', { name: 'Toggle enabled' }).click()
  await expect(activities).toHaveText('')
  await resolve(7, 'disabled-stale')
  await expect(activities).toHaveText('')
  await page.getByRole('button', { name: 'Toggle enabled' }).click()
  await expect.poll(requestCount).toBe(9)
  await expect(activities).toHaveText('latest')
  await resolve(8, 'reenabled')
  await expect(activities).toHaveText('reenabled')
})


test('thread hydration cannot replace a newer refresh', async ({ page }) => {
  await page.goto('/src/e2e-fixtures/index.html')
  await page.evaluate(() => import('/src/e2e-fixtures/automation-refresh.tsx'))
  const requestCount = () => page.evaluate(() => (window as any).activityRequests.length)
  const resolve = (index: number, id: string) => page.evaluate(async ([i, value]) => {
    (window as any).resolveActivity(i, value)
    await new Promise(resolve => setTimeout(resolve, 25))
  }, [index, id] as const)
  const activities = page.getByTestId('activities')
  await page.getByRole('button', { name: 'Add A' }).click()
  await page.getByRole('button', { name: 'Select A' }).click()
  await expect.poll(requestCount).toBe(1)
  await page.getByRole('button', { name: 'Hydrate A' }).click()
  await expect.poll(requestCount).toBe(2)
  await page.getByRole('button', { name: 'Refresh' }).click()
  await expect.poll(requestCount).toBe(3)
  await resolve(2, 'fresh')
  await expect(activities).toHaveText('fresh')
  await resolve(1, 'stale-hydration')
  await resolve(0, 'stale-selection')
  await expect(activities).toHaveText('fresh')
  await page.getByRole('button', { name: 'Select B' }).click()
  await expect.poll(requestCount).toBe(4)
  await page.getByRole('button', { name: 'Select A' }).click()
  await expect.poll(requestCount).toBe(5)
  await expect(activities).toHaveText('fresh')
})


test('live activity survives pending selection, refresh, and hydration snapshots', async ({ page }) => {
  await page.goto('/src/e2e-fixtures/index.html')
  await page.evaluate(() => import('/src/e2e-fixtures/automation-refresh.tsx'))
  const count = () => page.evaluate(() => (window as any).activityRequests.length)
  const resolve = (index: number, id: string) => page.evaluate(([i, value]) => (window as any).resolveActivity(i, value), [index, id] as const)
  const activities = page.getByTestId('activities')
  await page.getByRole('button', { name: 'Add A' }).click()
  await page.getByRole('button', { name: 'Select A' }).click()
  await expect.poll(count).toBe(1)
  await page.getByRole('button', { name: 'Live A' }).click()
  await resolve(0, 'selection')
  await expect(activities).toHaveText('selection,live')
  await page.getByRole('button', { name: 'Refresh' }).click()
  await expect.poll(count).toBe(2)
  await page.getByRole('button', { name: 'Live A' }).click()
  await resolve(1, 'refresh')
  await expect(activities).toHaveText('refresh,live')
  await page.getByRole('button', { name: 'Hydrate A' }).click()
  await expect.poll(count).toBe(3)
  await page.getByRole('button', { name: 'Live A' }).click()
  await resolve(2, 'hydrate')
  await expect(activities).toHaveText('hydrate,live')
})
